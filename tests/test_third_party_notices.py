"""THIRD-PARTY-NOTICES.txt exists, is current, and ships in both builds.

The file is generated by scripts/third_party_notices.py from the build venv's
installed package metadata plus hand-written entries (FFmpeg, PyAV, NVIDIA,
libiomp5md, fonts, ...). Both PyInstaller specs bundle it, with LICENSE, at
the resource root; src/notices.py finds it for Settings > About; the Windows
installer shows Waffler's own LICENSE. Offline.
"""
import ast
import re
import subprocess
import sys
from pathlib import Path

import pytest
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

import notices  # noqa: E402

NOTICES = ROOT / "THIRD-PARTY-NOTICES.txt"


def _text():
    return NOTICES.read_text(encoding="utf-8")


def _spec_datas(spec):
    tree = ast.parse((ROOT / spec).read_text(encoding="utf-8"))
    for node in ast.walk(tree):
        if isinstance(node, ast.Call) and getattr(node.func, "id", "") == "Analysis":
            for kw in node.keywords:
                if kw.arg == "datas":
                    lists = [n for n in ast.walk(kw.value) if isinstance(n, ast.List)]
                    return [tuple(ast.literal_eval(e)) for lst in lists for e in lst.elts]
    raise AssertionError(f"no datas in {spec}")


def test_the_notices_file_exists():
    assert NOTICES.is_file() and len(_text()) > 10_000


@pytest.mark.parametrize("needle", ["FFmpeg", "PyAV", "NVIDIA", "libiomp5md", "cuDNN", "cuBLAS",
                                    "gyan.dev", "--enable-gpl", "SIL Open Font License",
                                    "Lucide", "React", "GNU General Public License, version 3",
                                    "GNU Lesser General Public License, version 2.1"])
def test_the_notices_cover_the_bundled_binaries(needle):
    assert needle in _text()


def _top_level(req_file):
    out = []
    for line in (ROOT / req_file).read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            out.append(Requirement(line).name)
    return out


@pytest.mark.parametrize("name", sorted(set(_top_level("requirements.txt")
                                            + _top_level("requirements_windows.txt"))))
def test_every_top_level_requirement_is_in_the_notices(name):
    # Each package's heading starts with its name (case and -/_ aside).
    headings = {canonicalize_name(m.group(1))
                for m in re.finditer(r"(?m)^(\S+)(?: \S+)?  \[", _text())}
    assert canonicalize_name(name) in headings


def test_llama_cpp_python_is_in_the_notices():
    assert re.search(r"(?im)^llama[-_]cpp[-_]python", _text())


@pytest.mark.parametrize("spec", ["Waffler_mac.spec", "Waffler_windows.spec"])
def test_both_builds_bundle_the_notices_and_the_licence(spec):
    datas = _spec_datas(spec)
    assert ("THIRD-PARTY-NOTICES.txt", ".") in datas
    assert ("LICENSE", ".") in datas
    # Same place as the other root-level data the app reads.
    assert ("config.yaml", ".") in datas


def test_the_installer_shows_waffler_s_own_licence():
    iss_path = ROOT / "installer" / "windows" / "Waffler.iss"
    lines = [l.strip() for l in iss_path.read_text(encoding="utf-8").splitlines()
             if l.strip().startswith("LicenseFile=")]
    assert len(lines) == 1
    value = lines[0].split("=", 1)[1].strip()
    assert value, "LicenseFile is empty"
    target = (iss_path.parent / value.replace("\\", "/")).resolve()
    assert target.is_file() and target == (ROOT / "LICENSE").resolve()


def test_the_release_workflow_does_not_override_the_licence_file():
    wf = (ROOT / ".github" / "workflows" / "windows-release.yml").read_text(encoding="utf-8")
    assert "LicenseFile" not in wf
    assert not re.search(r"ISCC\.exe\"[^\n]*/D", wf)


def test_notices_path_finds_the_repository_file_in_dev():
    assert notices.notices_path() == NOTICES.resolve()
    assert notices.read_notices() == _text()


def test_notices_path_in_a_frozen_build(tmp_path, monkeypatch):
    (tmp_path / notices.NOTICES_NAME).write_text("hello", encoding="utf-8")
    monkeypatch.setattr(sys, "frozen", True, raising=False)
    monkeypatch.setattr(sys, "_MEIPASS", str(tmp_path), raising=False)
    assert notices.notices_path() == tmp_path / notices.NOTICES_NAME
    assert notices.read_notices() == "hello"


def test_a_missing_file_reads_as_empty(tmp_path, monkeypatch):
    monkeypatch.setattr(sys, "frozen", True, raising=False)
    monkeypatch.setattr(sys, "_MEIPASS", str(tmp_path), raising=False)
    monkeypatch.setattr(sys, "executable", str(tmp_path / "MacOS" / "Waffler"))
    assert notices.notices_path() is None
    assert notices.read_notices() == ""


def test_the_generator_check_passes():
    r = subprocess.run([sys.executable, str(ROOT / "scripts" / "third_party_notices.py"), "--check"],
                       capture_output=True, text=True, cwd=ROOT, timeout=120)
    said = r.stdout + r.stderr
    if r.returncode != 0 and "is not installed here" in said:
        # The check compares against the packages the file was generated with (the Mac
        # build's, llama-cpp-python among them). A test machine without them cannot say.
        pytest.skip("this environment lacks packages the notices were generated with")
    assert r.returncode == 0, said


def test_settings_about_offers_the_licences():
    """Settings > About has a Licences button that opens the bundled file."""
    html = (ROOT / "ui" / "index.html").read_text(encoding="utf-8")
    assert 'id="aboutLicences" data-onclick="openLicences()"' in html
    js = (ROOT / "ui" / "app.js").read_text(encoding="utf-8")
    assert "pywebview.api.open_licences()" in js
    app = (ROOT / "app.py").read_text(encoding="utf-8")
    fn = app[app.index("    def open_licences(self)"):]
    fn = fn[:fn.index("\n    def ", 10)]
    assert "_notices.notices_path()" in fn
