"""Where the bundled THIRD-PARTY-NOTICES.txt is, for Settings > About.

The file is generated by scripts/third_party_notices.py and put in both
builds by the spec files' datas, at the bundle's resource root next to
config.yaml and prompts/:

* Windows: <install folder>/_internal/THIRD-PARTY-NOTICES.txt (sys._MEIPASS);
* Mac: Waffler.app/Contents/Resources/THIRD-PARTY-NOTICES.txt, which
  PyInstaller also links from Contents/Frameworks (sys._MEIPASS);
* from the repository (not frozen): the repository root.
"""
from __future__ import annotations

import sys
from pathlib import Path
from typing import Optional

NOTICES_NAME = "THIRD-PARTY-NOTICES.txt"


def _candidates() -> list:
    if getattr(sys, "frozen", False):
        out = []
        meipass = getattr(sys, "_MEIPASS", None)
        if meipass:
            out.append(Path(meipass) / NOTICES_NAME)
        exe_dir = Path(sys.executable).resolve().parent
        out.append(exe_dir / "_internal" / NOTICES_NAME)          # Windows one-folder
        out.append(exe_dir.parent / "Resources" / NOTICES_NAME)   # Mac: Contents/MacOS -> Resources
        return out
    return [Path(__file__).resolve().parent.parent / NOTICES_NAME]


def notices_path() -> Optional[Path]:
    """The notices file, or None when it is not there."""
    for path in _candidates():
        try:
            if path.is_file():
                return path
        except OSError:
            continue
    return None


def read_notices() -> str:
    """The notices' text, or "" when the file is missing or unreadable."""
    path = notices_path()
    if path is None:
        return ""
    try:
        return path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return ""
