"""Safe paste.

Putting dictated text into another app by way of the clipboard has three ways
to hurt the user: it throws away whatever they had copied, it can fire while
the hotkey's modifier keys are still down (so the target sees Shift+Cmd+V or
Fn+Cmd+V), and when it silently fails the words are simply gone.

This module does the whole job in one place:

    snapshot every item/type on the pasteboard
      -> put the text on it
      -> wait until the hotkey's modifiers are physically up
      -> send Cmd+V (keycode resolved from the active keyboard layout)
      -> wait ~500 ms for the target app to read the pasteboard
      -> put the old contents back (only if nobody else wrote meanwhile)

and reports a ``PasteOutcome``: ``pasted``, ``unverified`` or ``failed``.
``failed`` never restores: the text stays on the clipboard so the user can
press Cmd+V themselves. The macOS pieces live in ``mac_input`` and are
lazily imported, so this module imports cleanly on Windows and in CI.

Nothing here logs or stores any text: the clipboard's old contents live in
memory for about a second, and the focused field is only compared by a
fingerprint.
"""

from __future__ import annotations

import sys
import threading
import time
from dataclasses import dataclass
from typing import Callable, List, Optional, Tuple

import mac_input
from mac_input import (
    BLOCKED,
    HOTKEY_MODIFIER_MASK,
    NONE,
    NOT_EDITABLE,
    OPAQUE,
    TEXT,
    FocusState,
)
import user_messages

# Re-exported so callers (and tests) can reach the keycode resolver from here.
resolve_v_keycode = mac_input.resolve_v_keycode

PASTED = "pasted"
UNVERIFIED = "unverified"
FAILED = "failed"

# Pasteboard markers (nspasteboard.org) that other apps put on data that must
# not be recorded or revived: password managers, other apps' own temporary
# pastes, synced/auto-generated copies.
CONCEALED_TYPE = "org.nspasteboard.ConcealedType"
TRANSIENT_TYPE = "org.nspasteboard.TransientType"
AUTOGENERATED_TYPE = "org.nspasteboard.AutoGeneratedType"
# Universal Clipboard: the data lives on another device and is fetched on
# demand, so reading every type could stall for seconds.
REMOTE_CLIPBOARD_TYPE = "com.apple.is-remote-clipboard"
_MARKER_REASONS = {
    CONCEALED_TYPE: "concealed",
    TRANSIENT_TYPE: "transient",
    AUTOGENERATED_TYPE: "auto_generated",
    REMOTE_CLIPBOARD_TYPE: "remote",
}

# A clipboard this big is not worth holding in memory for half a second, and
# reading it must not hold up the paste for long.
MAX_SNAPSHOT_BYTES = 128 * 1024 * 1024
SNAPSHOT_BUDGET_SECONDS = 2.0

# Settings: what happens to the clipboard after a paste (Mac).
AFTER_PASTE_RESTORE = "restore"
AFTER_PASTE_KEEP = "keep"
AFTER_PASTE_MODES = (AFTER_PASTE_RESTORE, AFTER_PASTE_KEEP)

# How long a paste waits for another clipboard operation before it carries on
# without restoring (only a wedged one holds the lock this long).
LOCK_WAIT_SECONDS = 3.0
# The Accessibility reads are cut off once a paste has used this long, so a
# hung target app (each read then runs to its own timeout) cannot push the
# paste past the pipeline's deadline.
VERIFY_BUDGET_SECONDS = 2.5

_PASTE_LOCK = threading.RLock()  # one clipboard operation at a time


@dataclass(frozen=True)
class PasteOutcome:
    """Result of a paste.

    ``status`` is ``pasted``, ``unverified`` or ``failed``. ``on_clipboard``
    is True when the dictation is on the clipboard now (it is not after a
    restore, which is the point). ``restored`` is True when the user's own
    clipboard was put back.
    """

    status: str
    reason: str = ""
    restored: bool = False
    on_clipboard: bool = False

    @property
    def ok(self) -> bool:
        return self.status != FAILED


@dataclass(frozen=True)
class Snapshot:
    """Every item on the pasteboard as ``((type, bytes), ...)`` rows.

    ``skipped`` is non-empty when the contents were deliberately not captured
    (``concealed``, ``transient``, ``auto_generated``, ``remote``, ``too_large``,
    ``slow`` or ``unreadable``); such a snapshot holds no data and restoring it
    does nothing. An empty clipboard is NOT skipped: ``items == ()`` and
    restoring it empties the clipboard again.
    """

    items: Tuple[Tuple[Tuple[str, bytes], ...], ...] = ()
    skipped: str = ""
    change_count: int = 0


class PasteTicket:
    """Shared by the pipeline and the paste thread.

    The pipeline stops waiting for a paste after its deadline and tells the
    user the text is on the clipboard. The paste thread may still be running,
    and must not then put the old clipboard back over the words it just
    promised, nor send its keystroke into whatever the user is doing by then.

    ``abandon`` and ``commit_restore`` take the same lock, so exactly one of
    them wins: either the restore has begun (the paste went in, and
    ``abandon`` says so) or it never will.
    """

    def __init__(self):
        self._lock = threading.Lock()
        self._abandoned = False
        self._restoring = False

    @property
    def abandoned(self) -> bool:
        return self._abandoned

    def abandon(self) -> bool:
        """The pipeline gave up waiting. True when the paste will now leave
        the text on the clipboard; False when it had already begun putting
        the user's clipboard back (so the paste is done)."""
        with self._lock:
            if self._restoring:
                return False
            self._abandoned = True
            return True

    def commit_restore(self) -> bool:
        """The paste thread is about to put the old clipboard back. False if
        the pipeline has given up: leave the text where it is."""
        with self._lock:
            if self._abandoned:
                return False
            self._restoring = True
            return True


# ── The pasteboard (macOS) ────────────────────────────────────────────────

class MacPasteboard:
    """Thin wrapper over an ``NSPasteboard`` (the general one by default)."""

    def __init__(self, pb=None, max_bytes: int = MAX_SNAPSHOT_BYTES,
                 budget: float = SNAPSHOT_BUDGET_SECONDS, clock: Callable[[], float] = time.monotonic):
        if pb is None:
            from AppKit import NSPasteboard
            pb = NSPasteboard.generalPasteboard()
        self._pb = pb
        self._max_bytes = max_bytes
        self._budget = budget
        self._clock = clock

    def change_count(self) -> int:
        return int(self._pb.changeCount())

    def snapshot(self) -> Snapshot:
        """Capture every item and every type (the bytes, not just the text).

        Types named ``dyn.*`` are kept: a flavour written under a non-UTI name
        (legacy ``declareTypes``) exists *only* as a ``dyn.*`` type.

        Contents carrying a concealed/transient/auto-generated marker are not
        captured at all: a password manager's secret must not be copied into
        our memory, nor revived on the clipboard (without its marker, clipboard
        managers would then record it). Universal Clipboard contents, anything
        over the size cap, anything slower than the time budget to read, and a
        clipboard we could not read at all are skipped too: restoring is then
        impossible, but the paste is never held up for long.
        """
        cc = self.change_count()
        items = list(self._pb.pasteboardItems() or [])
        for item in items:
            for t in item.types():
                reason = _MARKER_REASONS.get(str(t))
                if reason:
                    return Snapshot((), skipped=reason, change_count=cc)
        started = self._clock()
        total = 0
        rows: List[Tuple[Tuple[str, bytes], ...]] = []
        for item in items:
            row = []
            for t in item.types():
                data = item.dataForType_(str(t))
                if self._clock() - started > self._budget:
                    return Snapshot((), skipped="slow", change_count=cc)
                if data is None:
                    continue
                total += int(data.length())
                if total > self._max_bytes:
                    return Snapshot((), skipped="too_large", change_count=cc)
                row.append((str(t), bytes(data)))
            if row:
                rows.append(tuple(row))
        if items and not rows:
            # Something is on the clipboard but none of it could be read: do
            # not mistake that for an empty clipboard (restoring would clear it).
            return Snapshot((), skipped="unreadable", change_count=cc)
        return Snapshot(tuple(rows), change_count=cc)

    def current_text(self) -> str:
        """The plain text on the pasteboard right now ('' when it holds none).
        Only the copy fallback that reads a selection uses this
        (src/selection_copy.py); a paste never reads the clipboard."""
        from AppKit import NSPasteboardTypeString
        value = self._pb.stringForType_(NSPasteboardTypeString)
        return str(value) if value else ""

    def put_text(self, text: str, transient: bool = False) -> int:
        """Replace the pasteboard with ``text``; returns the new change count.

        ``transient=True`` adds the markers that tell clipboard managers not to
        record this copy (used for the half second before we put the user's
        clipboard back).
        """
        from AppKit import NSPasteboardItem, NSPasteboardTypeString
        from Foundation import NSData
        item = NSPasteboardItem.alloc().init()
        item.setString_forType_(text, NSPasteboardTypeString)
        if transient:
            for marker in (TRANSIENT_TYPE, AUTOGENERATED_TYPE):
                item.setData_forType_(NSData.data(), marker)
        # clearContents() returns the change count that is ours; writing the
        # items afterwards does not bump it. If it moved, someone else wrote.
        ours = int(self._pb.clearContents())
        if not self._pb.writeObjects_([item]):
            raise RuntimeError("pasteboard refused the write")
        if self.change_count() != ours:
            raise RuntimeError("pasteboard changed while writing")
        return ours

    def restore(self, snap: Optional[Snapshot], expect_change_count: int) -> bool:
        """Put ``snap`` back, but only if the pasteboard is still at
        ``expect_change_count`` (the count right after *our* write). If the user
        copied something else in the meantime we leave their copy alone."""
        if snap is None or snap.skipped:
            return False
        if self.change_count() != expect_change_count:
            return False
        if not snap.items:
            self._pb.clearContents()
            return True
        from AppKit import NSPasteboardItem
        from Foundation import NSData
        objs = []
        for row in snap.items:
            item = NSPasteboardItem.alloc().init()
            for t, data in row:
                item.setData_forType_(NSData.dataWithBytes_length_(data, len(data)), t)
            objs.append(item)
        self._pb.clearContents()
        if not self._pb.writeObjects_(objs):
            # The clipboard is now empty: tell the caller, which keeps the
            # dictation as a normal copy instead of leaving nothing at all.
            raise RuntimeError("could not write the restored items")
        return True


# ── Small pure pieces ─────────────────────────────────────────────────────

def wait_for_modifiers_released(flags: Callable[[], int], timeout: float,
                                sleep: Callable[[float], None] = time.sleep,
                                clock: Callable[[], float] = time.monotonic,
                                poll: float = 0.01) -> bool:
    """Block until none of Fn/Shift/Control/Option/Command is physically down.

    Returns True when they came up (or could not be read, which is treated as
    "nothing held"), False if ``timeout`` elapsed with a modifier still down.
    """
    deadline = clock() + timeout
    while True:
        try:
            held = int(flags()) & HOTKEY_MODIFIER_MASK
        except Exception:
            return True
        if not held:
            return True
        if clock() >= deadline:
            return False
        sleep(poll)


def classify_paste(before: Optional[FocusState], after: Optional[FocusState]) -> Tuple[str, str]:
    """Map the focused field before/after the keystroke to ``(status, reason)``.

    Verification is best effort. Apps that do not expose their text through
    Accessibility (Electron, terminals, many web views) are ``unverified``,
    never ``failed``: only a positive sign that nothing could have been
    pasted (nothing focused at all, or a button/checkbox/menu focused) fails. A text
    field whose text did not change is ``unverified`` too: custom editors
    (Google Docs and friends) keep a stale Accessibility value, and calling a
    successful paste "failed" would be worse than not knowing.
    """
    if before is None:
        return UNVERIFIED, "no_reader"
    if before.kind == NONE:
        return FAILED, "no_focus"
    if before.kind == NOT_EDITABLE:
        return FAILED, "not_editable"
    if before.kind == BLOCKED:
        return UNVERIFIED, "ax_unavailable"
    if before.kind != TEXT:
        return UNVERIFIED, "opaque"
    if after is None or after.kind != TEXT:
        return UNVERIFIED, "focus_changed"
    if after.fingerprint != before.fingerprint:
        return PASTED, ""
    return UNVERIFIED, "no_change"


# ── The paste sequence ────────────────────────────────────────────────────

def _noop_log(_msg: str) -> None:
    pass


class SafePaster:
    """Runs the snapshot -> write -> modifiers -> Cmd+V -> restore sequence.

    Every environment dependency is injected (pasteboard, modifier flags, key
    sender, keycode resolver, Accessibility reader, clock) so the whole
    sequence is testable without a keyboard, a clipboard or permissions.
    """

    def __init__(self, pasteboard, *, flags, keycode_resolver, send_key, focus_reader,
                 trusted=None, sleep=time.sleep, clock=time.monotonic,
                 restore_delay: float = 0.5, unconfirmed_extra_delay: float = 0.5,
                 modifier_timeout: float = 0.4, settle_delay: float = 0.05,
                 poll_interval: float = 0.1, verify_budget: float = VERIFY_BUDGET_SECONDS,
                 lock_wait: float = LOCK_WAIT_SECONDS, log=_noop_log):
        self.pb = pasteboard
        self._flags = flags
        self._keycode = keycode_resolver
        self._send_key = send_key
        self._focus = focus_reader
        self._trusted = trusted
        self._sleep = sleep
        self._clock = clock
        self.restore_delay = restore_delay
        self.unconfirmed_extra_delay = unconfirmed_extra_delay
        self.modifier_timeout = modifier_timeout
        self.settle_delay = settle_delay
        self.poll_interval = poll_interval
        self.verify_budget = verify_budget
        self.lock_wait = lock_wait
        self._log = log

    # -- helpers ---------------------------------------------------------

    def _wait(self, seconds: float) -> None:
        end = self._clock() + seconds
        while True:
            left = end - self._clock()
            if left <= 0:
                return
            self._sleep(min(self.poll_interval, left))

    def _read_focus(self, started: float) -> FocusState:
        # Past the budget (a hung app makes every read run to its timeout)
        # the paste stops looking and is simply unverified.
        if self._clock() - started > self.verify_budget:
            return FocusState(OPAQUE)
        try:
            return self._focus.read()
        except Exception:
            return FocusState(OPAQUE)

    def _is_trusted(self) -> Optional[bool]:
        if self._trusted is None:
            return None
        try:
            return self._trusted()
        except Exception:
            return None

    def _wait_for_late_paste(self, before: Optional[FocusState],
                             started: float) -> Optional[Tuple[str, str]]:
        """The paste is not confirmed after ``restore_delay``. A slow app may
        simply not have read the pasteboard yet, and restoring now would make it
        paste the user's OLD clipboard, so keep the dictation there a bit longer.
        With a readable text field, watch for the change; returns
        ``(PASTED, "")`` if it shows up, else None."""
        end = self._clock() + self.unconfirmed_extra_delay
        while self._clock() < end:
            self._sleep(min(self.poll_interval, max(end - self._clock(), 0.0)))
            if before is not None and before.kind == TEXT:
                after = self._read_focus(started)
                if after.kind == TEXT and after.fingerprint != before.fingerprint:
                    return PASTED, ""
        return None

    def _leave_as_plain_copy(self, text: str, our_count: Optional[int]) -> bool:
        """Make the text a normal, durable clipboard entry (drop the transient
        markers) -- but never over something the user copied after us. True
        when the text is on the clipboard."""
        try:
            if our_count is None or self.pb.change_count() == our_count:
                self.pb.put_text(text, transient=False)
                return True
        except Exception as e:
            self._log(f"[paste] could not rewrite plain copy: {type(e).__name__}")
        return False

    # -- the sequence ----------------------------------------------------

    def paste(self, text: str, restore: bool = True, settle_delay: Optional[float] = None,
              ticket: Optional[PasteTicket] = None) -> PasteOutcome:
        if not _PASTE_LOCK.acquire(timeout=self.lock_wait):
            # Something else has held the clipboard for seconds. Paste anyway,
            # but without a snapshot: restoring from two overlapping
            # sequences could put back the wrong thing.
            self._log("[paste] clipboard busy; pasting without restoring")
            return self._paste(text, False, settle_delay, ticket)
        try:
            return self._paste(text, restore, settle_delay, ticket)
        finally:
            _PASTE_LOCK.release()

    def _paste(self, text: str, restore: bool, settle_delay: Optional[float],
               ticket: Optional[PasteTicket]) -> PasteOutcome:
        started = self._clock()
        # Without Accessibility macOS drops the synthetic keystroke. Say so
        # up front instead of pretending, and keep the words on the clipboard.
        if self._is_trusted() is False:
            try:
                self.pb.put_text(text, transient=False)
            except Exception as e:
                self._log(f"[paste] clipboard write failed: {type(e).__name__}")
                return PasteOutcome(FAILED, "clipboard_error")
            self._log("[paste] outcome=failed reason=accessibility_off (keystroke not sent)")
            return PasteOutcome(FAILED, "accessibility_off", on_clipboard=True)

        snap = None
        if restore:
            try:
                snap = self.pb.snapshot()
            except Exception as e:
                self._log(f"[paste] snapshot failed ({type(e).__name__}); clipboard cannot be restored")
        try:
            ours = self.pb.put_text(text, transient=restore)
        except Exception as e:
            self._log(f"[paste] clipboard write failed: {type(e).__name__}")
            return PasteOutcome(FAILED, "clipboard_error")

        settle = self.settle_delay if settle_delay is None else settle_delay
        if settle:
            self._sleep(settle)
        if not wait_for_modifiers_released(self._flags, self.modifier_timeout, self._sleep, self._clock):
            self._log("[paste] modifier keys still down after the wait; pasting anyway")

        if ticket is not None and ticket.abandoned:
            # The pipeline stopped waiting while this was stuck. It has told
            # the user the text is on the clipboard, so leave it there and do
            # not type into whatever the user is doing now.
            on_clipboard = self._leave_as_plain_copy(text, ours) if restore else True
            self._log("[paste] gave up before the keystroke (the caller stopped waiting)")
            return PasteOutcome(FAILED, "gave_up", on_clipboard=on_clipboard)

        before = self._read_focus(started)
        try:
            self._send_key(self._keycode())
        except Exception as e:
            self._log(f"[paste] keystroke failed: {type(e).__name__}")
            on_clipboard = self._leave_as_plain_copy(text, ours) if restore else True
            return PasteOutcome(FAILED, "keystroke_error", on_clipboard=on_clipboard)

        # Give the target app time to read the pasteboard before we change it.
        self._wait(self.restore_delay)

        status, reason = classify_paste(before, self._read_focus(started))

        if status == UNVERIFIED:
            late = self._wait_for_late_paste(before, started)
            if late is not None:
                status, reason = late

        if status == FAILED:
            on_clipboard = self._leave_as_plain_copy(text, ours) if restore else True
            self._log(f"[paste] outcome=failed reason={reason}")
            return PasteOutcome(FAILED, reason, on_clipboard=on_clipboard)

        if not restore:
            self._log(f"[paste] outcome={status} reason={reason or '-'} restored=False (kept)")
            return PasteOutcome(status, reason, restored=False, on_clipboard=True)

        if ticket is not None and not ticket.commit_restore():
            # Abandoned while waiting: the words stay on the clipboard.
            on_clipboard = self._leave_as_plain_copy(text, ours)
            self._log(f"[paste] outcome={status} restore skipped (the caller stopped waiting)")
            return PasteOutcome(status, reason, restored=False, on_clipboard=on_clipboard)

        restored = False
        errored = False
        try:
            restored = bool(self.pb.restore(snap, ours))
        except Exception as e:
            errored = True
            self._log(f"[paste] restore failed: {type(e).__name__}")
        on_clipboard = False
        if not restored:
            # Could not give the old clipboard back (nothing captured, the
            # user copied something, or the write failed after clearing it):
            # keep our text as a normal copy. After a failed restore write
            # the clipboard is empty and ours to refill; otherwise only if
            # it is still our write.
            on_clipboard = self._leave_as_plain_copy(text, None if errored else ours)
        self._log(f"[paste] outcome={status} reason={reason or '-'} restored={restored}")
        return PasteOutcome(status, reason, restored=restored, on_clipboard=on_clipboard)


# ── Public entry points used by clipboard.py / app.py ─────────────────────

_logger: Callable[[str], None] = _noop_log
_paster: Optional[SafePaster] = None


def set_logger(fn: Callable[[str], None]) -> None:
    """Route this module's one-line diagnostics (never any text content)."""
    global _logger, _paster
    _logger = fn or _noop_log
    _paster = None


def _default_paster() -> SafePaster:
    global _paster
    if _paster is None:
        from mac_input import AXFocusReader, modifier_flags, send_command_key, v_keycode_for_current_layout
        from mac_permissions import accessibility_trusted
        _paster = SafePaster(
            MacPasteboard(),
            flags=modifier_flags,
            keycode_resolver=v_keycode_for_current_layout,
            send_key=send_command_key,
            focus_reader=AXFocusReader(),
            trusted=accessibility_trusted,
            log=lambda m: _logger(m),
        )
    return _paster


def warm_up() -> None:
    """Build the default paster and load Accessibility now, so the first
    real paste does not pay for it. Safe to call from any thread."""
    if sys.platform != "darwin":
        return
    try:
        _default_paster()._focus.warm()
    except Exception as e:
        _logger(f"[paste] warm-up skipped: {type(e).__name__}")


def copy_text(text: str) -> bool:
    """Put ``text`` on the clipboard as an ordinary copy. True on success.

    The long-standing way (pyperclip), on every platform. Waits its turn
    behind a paste in progress so the two do not interleave, but never for
    long: a wedged paste must not stop a plain copy.
    """
    locked = _PASTE_LOCK.acquire(timeout=LOCK_WAIT_SECONDS)
    try:
        import pyperclip
        pyperclip.copy(text)
        return True
    except Exception as e:
        _logger(f"[clipboard] copy failed: {type(e).__name__}")
        return False
    finally:
        if locked:
            _PASTE_LOCK.release()


def _windows_ctrl_v(hwnd=None) -> None:
    """Restore focus to ``hwnd`` and send Ctrl+V (the long-standing approach)."""
    import ctypes
    KEYEVENTF_KEYUP = 0x0002
    VK_CONTROL = 0x11
    VK_V = 0x56
    if hwnd:
        ctypes.windll.user32.SetForegroundWindow(hwnd)
        time.sleep(0.15)  # let window regain focus
    ctypes.windll.user32.keybd_event(VK_CONTROL, 0, 0, 0)
    ctypes.windll.user32.keybd_event(VK_V, 0, 0, 0)
    time.sleep(0.05)
    ctypes.windll.user32.keybd_event(VK_V, 0, KEYEVENTF_KEYUP, 0)
    ctypes.windll.user32.keybd_event(VK_CONTROL, 0, KEYEVENTF_KEYUP, 0)


def send_paste_keystroke(window_handle=None) -> None:
    """Send only the paste keystroke (the clipboard already holds the text)."""
    if sys.platform == "win32":
        _windows_ctrl_v(window_handle)
        return
    from mac_input import modifier_flags, send_command_key, v_keycode_for_current_layout
    time.sleep(0.05)
    wait_for_modifiers_released(modifier_flags, 0.4)
    send_command_key(v_keycode_for_current_layout())


def paste_text(text: str, window_handle=None, restore: bool = True,
               settle_delay: Optional[float] = None,
               ticket: Optional[PasteTicket] = None) -> PasteOutcome:
    """Paste ``text`` into the focused app and report what happened.

    macOS: the full safe sequence. Windows: the existing copy + Ctrl+V, which
    cannot verify or restore the clipboard (``restore`` is ignored there).
    """
    if sys.platform == "darwin":
        return _default_paster().paste(text, restore=restore, settle_delay=settle_delay,
                                       ticket=ticket)
    if not copy_text(text):
        return PasteOutcome(FAILED, "clipboard_error")
    if sys.platform == "win32":
        try:
            if settle_delay:
                time.sleep(settle_delay)
            if ticket is not None and ticket.abandoned:
                return PasteOutcome(FAILED, "gave_up", on_clipboard=True)
            _windows_ctrl_v(window_handle)
        except Exception as e:
            _logger(f"[paste] Ctrl+V failed: {type(e).__name__}")
            return PasteOutcome(FAILED, "keystroke_error", on_clipboard=True)
        return PasteOutcome(UNVERIFIED, "no_verification", on_clipboard=True)
    return PasteOutcome(FAILED, "unsupported_platform", on_clipboard=True)


# ── Settings ──────────────────────────────────────────────────────────────

def restore_after_paste(settings: Optional[dict]) -> bool:
    """True when the user's clipboard should be put back after a paste.

    ``clipboard_after_paste`` is ``"restore"`` (default) or ``"keep"`` (leave
    the dictation on the clipboard, the behaviour before this setting existed).
    Anything else counts as the default. Windows ignores it.
    """
    return (settings or {}).get("clipboard_after_paste", AFTER_PASTE_RESTORE) != AFTER_PASTE_KEEP


# ── Failed-paste messaging ────────────────────────────────────────────────

_DISMISS = {"label": "Dismiss", "action": "dismiss", "kind": "secondary"}


def paste_failure_toast(outcome: PasteOutcome, platform: str = None) -> dict:
    """Toast fields (``heading``, ``body``, ``buttons``) for a failed paste.
    ``buttons`` is None when the toast's usual Dismiss is all it needs."""
    platform = platform or sys.platform
    heading, body = user_messages.paste_failed_message(outcome.reason, platform)
    if outcome.reason == "accessibility_off":
        buttons = [{"label": "Open Settings", "action": "open_ax_settings", "kind": "primary"},
                   dict(_DISMISS)]
    elif outcome.reason == "clipboard_error":
        buttons = None
    else:
        buttons = [{"label": "Copy again", "action": "copy_last", "kind": "primary"},
                   dict(_DISMISS)]
    return {"heading": heading, "body": body, "buttons": buttons}


# The notifier's "paste_failed" kind keeps this gap (src/notifier.py).
PASTE_FAILURE_GAP_SECONDS = 30


def report_paste_failure(outcome: Optional[PasteOutcome], notifier,
                         platform: str = None) -> Optional[dict]:
    """Toast fields if ``outcome`` is a failure that may be announced now
    (the notifier allows "paste_failed" at most once per 30 s), else None.
    ``notifier`` is a src/notifier.py Notifier, or anything with ``claim``."""
    if outcome is None or outcome.status != FAILED:
        return None
    if not notifier.claim("paste_failed"):
        return None
    return paste_failure_toast(outcome, platform)


# ── Paste last / copy last ────────────────────────────────────────────────

# Journal entries that are not dictations (a rewrite of selected text, a spoken
# command): "Paste last" is the last thing that was dictated. A test keeps this
# the same as src/history_meta.py NON_DICTATION_KINDS, which this module does
# not import.
_NOT_A_DICTATION = ("transform", "command")


class LastResult:
    """The last text Waffler produced, for "paste last" and "copy last".

    Kept in memory; after a restart it falls back to the newest usable item in
    the history (``history_loader`` returns the history list, oldest first).
    """

    def __init__(self, history_loader: Optional[Callable[[], list]] = None):
        self._history_loader = history_loader
        self._text = ""
        self._cleared = False
        self._lock = threading.Lock()

    def set(self, text: str) -> None:
        if not text or not text.strip():
            return
        with self._lock:
            self._text = text
            self._cleared = False

    def clear(self) -> None:
        """Forget it, and do not fall back to the history either (the user
        deleted their data)."""
        with self._lock:
            self._text = ""
            self._cleared = True

    def swap(self, old: str, new: str = "") -> None:
        """The entry whose words are ``old`` was deleted, or redone with
        ``new`` words: "paste last" must not bring the old words back. Does
        nothing when the last result is something else. With no ``new`` it
        falls back to the history, as after a restart."""
        with self._lock:
            if old and self._text == old:
                self._text = new if new and new.strip() else ""

    def get(self) -> str:
        with self._lock:
            if self._text:
                return self._text
            if self._cleared or self._history_loader is None:
                return ""
            loader = self._history_loader
        try:
            history = loader() or []
        except Exception:
            return ""
        for item in reversed(history):
            if not isinstance(item, dict) or item.get("failed") or item.get("kind") in _NOT_A_DICTATION:
                continue
            # What the person made of it in the Journal, if they edited it
            # (src/history_meta.py final_text, which this module does not import).
            edited = item.get("edited_text")
            text = edited if isinstance(edited, str) and edited.strip() \
                else (item.get("styled") or item.get("text") or "")
            if isinstance(text, str) and text.strip():
                return text
        return ""

    def word_count(self) -> int:
        """Words in the last result: what the menu shows instead of the text."""
        return len(self.get().split())
